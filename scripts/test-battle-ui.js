'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const app = fs.readFileSync('js/app.js', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');
const css = fs.readFileSync('css/battle-ui-v35.css', 'utf8');
const gen9Ui = fs.readFileSync('js/patches/v27-gen9-battle-ui.js', 'utf8');
const switchPatch = fs.readFileSync('js/patches/v39-team-preview-switch-cinematics.js', 'utf8');
const worker = fs.readFileSync('js/gen9-local-engine.worker.entry.js', 'utf8');
assert.doesNotThrow(() => new Function(gen9Ui), 'Showdown team preview UI must parse');
assert.doesNotThrow(() => new Function(switchPatch), 'switch cinematic patch must parse');
assert.match(html, /v39-team-preview-switch-cinematics\.js/, 'v39 team preview and switch patch must load');
assert.match(gen9Ui, /data-g9="team-ready"/, 'Showdown UI must let the player confirm their lineup');
assert.match(gen9Ui, /Date\.now\(\)\+120000/, 'Showdown team preview must use a two-minute countdown');
assert.match(gen9Ui, /animateSwitchOut\("player"\)/, 'Showdown manual switches must animate the outgoing Pokémon');
assert.match(worker, /makePreviewRequest\(playerTeam,"p1"\)/, 'CPU worker must show the player a prebattle team preview');
assert.match(worker, /action\?\.teamOrder/, 'CPU worker must validate the submitted team order');
assert.match(app, /PokemonChampions2DSwitchCinematics\?\.beforeSwitch/, 'standard battle must animate switch recalls');
assert.match(app, /afterEndTurn\?\.\(b,v39ActiveBefore\)/, 'standard battle must animate automatic enemy replacements');
const start = app.indexOf('function renderBattlePage()');
const end = app.indexOf('\nfunction abilityTriggerOnMove', start);
assert.ok(start >= 0 && end > start, 'battle render function must exist');
const render = app.slice(start, end);
assert.match(render, /data-action="select-move"/, 'move buttons must remain clickable');
assert.doesNotMatch(render, /data-action="confirm-move"|data-action="execute-double"|double-action-status/, 'no extra confirm/finish buttons');
assert.match(render, /class="battlefield \$\{isDouble\?'is-double'/, 'double battle must expose its compact layout class');
assert.doesNotMatch(render, /playerHpStrip/, 'player HP must not be rendered as a separate strip');
assert.match(app, /case 'select-move':\{[\s\S]*?await executeTurn\(\[action\]\)/, 'selecting a move must execute a single battle action');
assert.match(app, /function nextDoubleActionSlot\([\s\S]*?function collectDoubleActions\(/, 'double battle must auto-advance and collect actions');
assert.match(app, /case 'switch-to':\{[\s\S]*?nextDoubleActionSlot\(b\)[\s\S]*?collectDoubleActions\(b\)/, 'double switches must use the same auto-advance flow');
assert.match(css, /\.battlefield \.combat-info\.enemy\{left:auto!important;right:12px!important;top:12px!important/, 'opponent HP must be top-right');
assert.match(css, /\.battlefield \.combat-info\.player\{display:block!important;left:12px!important;right:auto!important;bottom:12px!important/, 'player HP must be bottom-left and visible');
assert.match(css, /\.battlefield\.is-double \.combat-info\.enemy\.slot-1/, 'second opponent HP card must stack within the right half');
assert.match(css, /\.battlefield\.is-double \.combat-info\.player\.slot-1/, 'second player HP card must stack within the left half');
assert.match(css, /grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/, 'moves must use a compact two-column layout');
assert.match(html, /battle-ui-v35\.css/, 'v35 battle HUD styles must be loaded');
console.log('PASS: HP cards stay in opposite corners, doubles use compact half-width cards, and move clicks execute without a confirmation button.');
